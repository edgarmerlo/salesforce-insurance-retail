require('dotenv').config();

async function queryAgentforce(customerName, timeoutMs = 10000) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

  const url = `${process.env.SALESFORCE_INSTANCE_URL}/services/data/v68.0/actions/custom/generateAiAgentResponse/Retail_Insurance_Helper`;
  console.log(`[AGENTFORCE LIVE] Invoking Agentforce for customer: "${customerName}"...`);

  try {
    const response = await fetch(url, {
      method: 'POST',
      signal: controller.signal,
      headers: {
        'Authorization': `Bearer ${process.env.SALESFORCE_ACCESS_TOKEN}`,
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        inputs: [{
          userMessage: `Customer ${customerName} is requesting to cancel their policy. Fetch their purchases and policy, and provide the personalized retention pitch.`
        }]
      })
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      throw new Error(`Agentforce HTTP Error ${response.status}: ${response.statusText}`);
    }

    const result = await response.json();
    if (result && result[0] && result[0].isSuccess && result[0].outputValues) {
      const rawAgentResponse = result[0].outputValues.agentResponse;
      let aiPitch = rawAgentResponse;
      try {
        const parsed = JSON.parse(rawAgentResponse);
        if (parsed.value) aiPitch = parsed.value;
      } catch (ignored) {}

      console.log(`✅ [AGENTFORCE SUCCESS] Live pitch generated by Salesforce AI for "${customerName}"`);
      return {
        customerName,
        aiPitch,
        isLive: true
      };
    }

    throw new Error('Agentforce did not return valid output values.');
  } catch (error) {
    clearTimeout(timeoutId);
    throw error;
  }
}

module.exports = {
  queryAgentforce
};
